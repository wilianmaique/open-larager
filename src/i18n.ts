export const dictionaries: Record<Locale, Dictionary> = { en, 'pt-BR': pt, es, 'zh-CN': zh, hi };
export function detectLocale(language: string): Locale {
  const value = language.toLowerCase().replace('_', '-');
  if (value.startsWith('pt')) return 'pt-BR';
  if (value.startsWith('es')) return 'es';
  if (value.startsWith('zh')) return 'zh-CN';
  if (value.startsWith('hi')) return 'hi';
  return 'en';
}
export function translator(locale: Locale) {
  return (key: Key, values: Record<string, string | number> = {}): string =>
    dictionaries[locale][key].replace(/\{(\w+)\}/g, (_, name: string) =>
      String(values[name] ?? `{${name}}`),
    );
}
